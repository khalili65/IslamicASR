def write_summary(path: Path, session: str, stem: str) -> None:
    m = SESSION_META[session]
    lines = [
        f"# خلاصه — {m['title']}",
        "",
        f"**مدرس:** حجت‌الاسلام قاسمیان · **دوره:** انسان کامل · **جلسه:** {session}",
        "",
        "## خلاصهٔ کوتاه",
        "",
        m["summary_short"],
        "",
        "## فهرست مطالب / نقشهٔ جلسه",
        "",
    ]
    for i, item in enumerate(m["outline"], 1):
        lines.append(f"{i}. {item}")
    lines += ["", "## نکات کلیدی", ""]
    for t in m["takeaways"]:
        lines.append(f"- {t}")
    lines += ["", "## اصطلاحات و منابع", ""]
    for term, gloss in m["glossary"]:
        lines.append(f"- **{term}:** {gloss}")
    lines += [
        "",
        "---",
        "",
        f"_خلاصه توسط مدل بر اساس `{stem}.corrected.md`؛ ادعای تازه‌ای افزوده نشده است._",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")


def post_clarity(t: str, session: str) -> str:
    """Session-specific clarity + forced citation inserts near lecturer cues."""
    # Consolidate split Ra'd opening quotes (tolerate diacritic variants)
    t = re.sub(
        r'«وَيَقُولُ الَّذِينَ كَفَرُوا لَسْتَ مُرْسَلًا»\s*«قُلْ كَفَىٰ بِاللَّهِ شَهِيدًا بَيْنِي وَبَيْنَكُمْ وَمَنْ عِنْدَهُ عِلْمُ الْكِتَابِ»',
        "«" + RAD_43 + "»",
        t,
        count=2,
    )
    t = re.sub(
        r'«وَيَقُولُ الَّذِينَ كَفَرُوا لَسْتَ مُرْسَلًا»\s*\.?\s*«قُلْ كَفَىٰ بِاللَّهِ شَهِيدًا بَيْنِي وَبَيْنَكُمْ وَمَنْ عِندَهُ عِلْمُ الْكِتَابِ»',
        "«" + RAD_43 + "»",
        t,
        count=2,
    )
    t = t.replace("سوره مائده که احقاف آیه شوندم", "سورهٔ مبارکهٔ احقاف، آیهٔ شانزده")
    t = t.replace("سوره مائده که احقاف", "سورهٔ مبارکهٔ احقاف")

    if session == "062" and "احقاف" in t and AHQAF_16 not in t:
        t = re.sub(
            r'(سورهٔ مبارکهٔ احقاف، آیهٔ شانزده\.?\s*صفحه پونصد و چهار\.)',
            r'\1\n\n' + AHQAF_16 + '\n\n',
            t,
            count=1,
        )
        if AHQAF_16 not in t:
            t = t.replace(
                "سورهٔ مبارکهٔ احقاف",
                "سورهٔ مبارکهٔ احقاف. " + AHQAF_16,
                1,
            )

    if session == "062" and FAJR_27_30 not in t and "النفس المطمئنة" in t.replace("َ", "").replace("ِ", ""):
        pass
    if session == "062" and "یا أیتها النفس" not in t and "يَا أَيَّتُهَا النَّفْسُ" not in t:
        # try restore from common ASR block already partially fixed in persian_fixes
        if "ارجعی الی ربک" in t or "ارجعي إلى ربك" in t:
            t = re.sub(
                r'ي[اآ] أَ?يَّتُهَا النَّفْسُ الْمُطْمَئِنَّةُ.*?وَادْخُلِي جَنَّتِي\.?',
                FAJR_27_30,
                t,
                count=1,
                flags=re.DOTALL,
            )

    if session == "063" and "نمل آیه چهل" in t and NAML_40 not in t:
        t = t.replace(
            "سوره مبارکه نمل آیه چهل . صفحه سیصد و هشتاد .",
            "سورهٔ مبارکهٔ نمل آیهٔ چهل. صفحهٔ ۳۸۰.\n\n"
            + NAML_38 + "\n\n" + NAML_39 + "\n\n" + NAML_40 + "\n\n",
            1,
        )

    # leftover broken quote wrappers around ayah inserts
    t = re.sub(r'بعد که «\s*\n+', "بعد که\n\n", t)
    t = re.sub(r'»\s*تو اصلاً رسول نیستی', " تو اصلاً رسول نیستی", t)
    t = re.sub(r'\[سخنرانی در پس زمینه\]\s*', "", t)
    return t


def process_session(nnn: str) -> dict:
    folder = BASE / nnn
    cleaned = next(folder.glob("*.cleaned.txt"))
    stem = cleaned.name.replace(".cleaned.txt", "")
    raw = cleaned.read_text(encoding="utf-8")
    if "--- Segments ---" in raw:
        raw = raw.split("--- Segments ---")[0]
    raw_len = len(raw.strip())

    text = clean_noise(raw)
    text = apply_persian_fixes(text)
    text, log = fix_citations(text)
    text = post_clarity(text, nnn)

    if AHQAF_16 in text and not any(x["ref"].startswith("Quran 46:16") for x in log):
        log.append({
            "ref": "Quran 46:16",
            "fix": "inserted verified Ahqaf 16 at lecturer cue",
            "src": "https://api.alquran.cloud/v1/ayah/46:16",
        })
    if NAML_40 in text and not any("27:40" in x["ref"] for x in log):
        log.append({
            "ref": "Quran 27:38–40",
            "fix": "inserted verified Naml block at lecturer cue",
            "src": "https://api.alquran.cloud/v1/ayah/27:40",
        })

    # Ensure opening ayah present in canonical form early
    if RAD_43 not in text and ("رعد" in text[:800] or "علم الكتاب" in text[:1200]):
        m = re.search(r"(اللهم صل على محمد و آل محمد\.?\s*)", text)
        if m:
            pos = m.end()
            text = text[:pos] + f"\n\n{RAD_43}\n\n" + text[pos:]
            if not any(x["ref"].startswith("Quran 13:43") for x in log):
                log.insert(0, {
                    "ref": "Quran 13:43",
                    "fix": "inserted verified form near opening citation",
                    "src": "https://api.alquran.cloud/v1/ayah/13:43",
                })

    body = paragraphize(text)
    corr_txt = body + format_corrections_log(log)
    corr_txt_path = folder / f"{stem}.corrected.txt"
    corr_txt_path.write_text(corr_txt + "\n", encoding="utf-8")

    md_continuous = wrap_ayahs_in_md(text)
    # Clean residual broken wrappers after HTML insertion
    md_continuous = re.sub(r'بعد که «\s*\n+', "بعد که\n\n", md_continuous)
    md_continuous = re.sub(r'»\s*(تو اصلاً رسول نیستی)', r"\1", md_continuous)
    md_body = insert_headings(paragraphize_preserving_ayah_html(md_continuous), nnn)
    meta = SESSION_META[nnn]
    md = (
        MD_BANNER.format(nnn=nnn, title=meta["title"], focus=meta["focus"])
        + "\n"
        + md_body
        + "\n"
        + MD_FOOTER
        + "\n"
        + format_corrections_log(log)
        + "\n"
    )
    corr_md_path = folder / f"{stem}.corrected.md"
    corr_md_path.write_text(md, encoding="utf-8")

    summary_path = folder / f"{stem}.summary.md"
    write_summary(summary_path, nnn, stem)

    return {
        "session": nnn,
        "stem": stem,
        "cleaned_chars": raw_len,
        "corrected_txt_chars": len(corr_txt_path.read_text(encoding="utf-8")),
        "corrected_md_chars": len(corr_md_path.read_text(encoding="utf-8")),
        "summary_chars": len(summary_path.read_text(encoding="utf-8")),
        "ratio": len(body) / raw_len if raw_len else 0,
        "citations": len(log),
    }


def main():
    for nnn in ["062", "063"]:
        r = process_session(nnn)
        print(
            f"{nnn}: cleaned={r['cleaned_chars']} txt={r['corrected_txt_chars']} "
            f"md={r['corrected_md_chars']} sum={r['summary_chars']} "
            f"ratio={r['ratio']:.2%} cites={r['citations']}"
        )


if __name__ == "__main__":
    main()
