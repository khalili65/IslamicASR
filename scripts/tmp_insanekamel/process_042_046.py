def build_summary(nnn: str, stem: str) -> str:
    meta = SESSION_META[nnn]
    outline = "\n".join(f"{i}. {x}" for i, x in enumerate(meta["outline"], 1))
    takes = "\n".join(f"- {x}" for x in meta["takeaways"])
    gloss = "\n".join(f"- **{a}:** {b}" for a, b in meta["glossary"])
    return f"""# خلاصه — {meta['title']}

**مدرس:** حجت‌الاسلام قاسمیان · **دوره:** انسان کامل · **جلسه:** {nnn}

## خلاصهٔ کوتاه

{meta['summary_short']}

## فهرست مطالب / نقشهٔ جلسه

{outline}

## نکات کلیدی

{takes}

## اصطلاحات و منابع

{gloss}

---

_خلاصه توسط مدل بر اساس `{stem}.corrected.md`؛ ادعای تازه‌ای افزوده نشده است._
"""


def process_one(nnn: str) -> dict:
    folder = BASE / nnn
    cleaned = next(folder.glob("*.cleaned.txt"))
    stem = cleaned.name.replace(".cleaned.txt", "")
    raw = cleaned.read_text(encoding="utf-8")
    t = clean_noise(raw)
    t, log = fix_citations(t, nnn)
    t = apply_persian_fixes(t)
    t = paragraphize(t)
    # Ensure opening greeting cleaned
    t = t.replace("سلام عليكم ورحمة الله.", "السلام علیکم و رحمة الله.")
    t = t.replace("أعوذ بالله من الشيطان الرجيم.", "أعوذ بالله من الشيطان الرجیم.")
    t = t.replace("اعوذ بالله من الشيطان الرجيم.", "أعوذ بالله من الشيطان الرجیم.")

    corr_txt = folder / f"{stem}.corrected.txt"
    corr_md = folder / f"{stem}.corrected.md"
    summ = folder / f"{stem}.summary.md"

    header_txt = (
        f"# {SESSION_META[nnn]['title']}\n"
        f"مدرس: حجت‌الاسلام قاسمیان · دوره: انسان کامل · جلسه: {nnn}\n"
        f"منبع: {cleaned.name} (Segments حذف شده)\n\n"
    )
    corr_txt.write_text(header_txt + t + "\n\n## Corrections log\n" + "\n".join(
        f"- {e['ref']}: {e['fix']} ({e['src']})" for e in log
    ) + "\n", encoding="utf-8")

    md = build_md(nnn, t, log)
    corr_md.write_text(md, encoding="utf-8")
    summ.write_text(build_summary(nnn, stem), encoding="utf-8")

    ratio = len(t) / max(len(raw), 1)
    return {
        "nnn": nnn,
        "stem": stem,
        "raw": len(raw),
        "corrected": len(t),
        "ratio": round(ratio, 2),
        "log_n": len(log),
        "files": [corr_txt.name, corr_md.name, summ.name],
    }


def main():
    results = []
    for n in range(42, 47):
        results.append(process_one(f"{n:03d}"))
    for r in results:
        print(
            f"{r['nnn']}: ratio={r['ratio']} raw={r['raw']} corr={r['corrected']} "
            f"fixes={r['log_n']} → {', '.join(r['files'])}"
        )


if __name__ == "__main__":
    main()
