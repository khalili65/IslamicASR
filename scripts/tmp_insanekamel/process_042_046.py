def clean_noise(t: str) -> str:
    t = NOISE.sub("", t)
    t = re.sub(r"[ \t]{2,}", " ", t)
    t = re.sub(r" *\n *", "\n", t)
    t = re.sub(r"\n{3,}", "\n\n", t)
    return t.strip()


def apply_persian_fixes(t: str) -> str:
    for a, b in PERSIAN_FIXES:
        t = t.replace(a, b)
    return t


def paragraphize(t: str) -> str:
    """Split long lines into readable paragraphs on sentence boundaries."""
    lines = [ln.strip() for ln in t.split("\n") if ln.strip()]
    paras: list[str] = []
    for ln in lines:
        if len(ln) < 420:
            paras.append(ln)
            continue
        # split on Persian/Arabic sentence enders, keep chunks ~250–450 chars
        parts = re.split(r"(?<=[\.؟!۔])\s+", ln)
        buf = ""
        for p in parts:
            if not p:
                continue
            if not buf:
                buf = p
            elif len(buf) + 1 + len(p) < 420:
                buf = buf + " " + p
            else:
                paras.append(buf)
                buf = p
        if buf:
            paras.append(buf)
    return "\n\n".join(paras)


def replace_ayah_block(t: str, start_markers: list[str], end_markers: list[str], repl: str, log: list, ref: str) -> str:
    """Replace a contiguous Arabic-heavy block between markers with verified text."""
    # Find earliest start
    start = -1
    used = None
    for m in start_markers:
        i = t.find(m)
        if i != -1 and (start == -1 or i < start):
            start = i
            used = m
    if start < 0:
        return t
    # search forward for end within 800 chars
    window = t[start : start + 1200]
    end_rel = -1
    for m in end_markers:
        j = window.find(m)
        if j != -1:
            end_rel = max(end_rel, j + len(m))
    if end_rel < 0:
        # fallback: take until first Persian-heavy stretch after 40 chars of arabic
        m2 = re.search(r"[\u0600-\u06FF]{10,}[.،]?\s+(?:صلوات|یه |این |خب|عرض|بحث|صفحه)", window[40:])
        if m2:
            end_rel = 40 + m2.start()
        else:
            return t
    new = t[:start] + repl + t[start + end_rel :]
    log.append(
        {
            "ref": ref,
            "fix": f"replaced garbled block starting «{used[:40]}…»",
            "src": f"https://api.alquran.cloud/v1/ayah/{ref}/quran-uthmani",
        }
    )
    return new


