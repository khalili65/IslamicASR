def paragraphize(t: str) -> str:
    parts = re.split(r"(?<=[.؟!。])\s+", t)
    paras, buf = [], []
    for p in parts:
        p = p.strip()
        if not p:
            continue
        buf.append(p)
        if len(buf) >= 3 or len(" ".join(buf)) > 480:
            paras.append(" ".join(buf))
            buf = []
    if buf:
        paras.append(" ".join(buf))
    return "\n\n".join(paras)


def paragraphize_preserving_ayah_html(t: str) -> str:
    chunks = re.split(
        r'(<p class="ayah-ar"[\s\S]*?</p>\s*\n\s*> \*\*ترجمهٔ فارسی[\s\S]*?\n)',
        t,
    )
    out = []
    for ch in chunks:
        if ch.startswith('<p class="ayah-ar"'):
            out.append(ch.strip())
        elif ch.strip():
            out.append(paragraphize(ch))
    return "\n\n".join(out)


def wrap_ayahs_in_md(body: str, keys: list[str]) -> str:
    # longest first
    items = sorted(((k, plain(k)) for k in keys if k in AY), key=lambda x: -len(x[1]))
    for key, ar in items:
        if ar not in body:
            continue
        idx = body.find(ar)
        if "ayah-ar" in body[max(0, idx - 80) : idx]:
            continue
        block = AYAH_HTML.format(
            ar=ar, ref=REF_FA.get(key, key), fa=FA.get(key, "—")
        )
        body = body.replace(ar, "\n\n" + block + "\n\n", 1)
    return body


def insert_headings(body: str, headings: list[tuple[float, str]]) -> str:
    paras = body.split("\n\n")
    n = max(len(paras), 1)
    cuts = []
    for frac, title in headings:
        idx = min(int(frac * n), n - 1)
        cuts.append((idx, title))
    used = set()
    for idx, title in sorted(cuts, key=lambda x: -x[0]):
        while idx in used and idx > 0:
            idx -= 1
        used.add(idx)
        paras[idx] = f"{title}\n\n{paras[idx]}"
    return "\n\n".join(paras)


