def paragraphize(t: str) -> str:
    # Split on sentence-ish boundaries into readable paragraphs (~3–5 sentences)
    parts = re.split(r"(?<=[.؟!。])\s+", t)
    paras = []
    buf = []
    for p in parts:
        p = p.strip()
        if not p:
            continue
        buf.append(p)
        if len(buf) >= 3 or len(" ".join(buf)) > 450:
            paras.append(" ".join(buf))
            buf = []
    if buf:
        paras.append(" ".join(buf))
    return "\n\n".join(paras)


def paragraphize_preserving_ayah_html(t: str) -> str:
    """Paragraphize Persian prose without breaking wrapped ayah HTML blocks."""
    chunks = re.split(
        r'(<p class="ayah-ar"[\s\S]*?</p>\s*\n\s*> \*\*ترجمهٔ فارسی[\s\S]*?\n)',
        t,
    )
    out = []
    for ch in chunks:
        if ch.startswith('<p class="ayah-ar"'):
            out.append(ch.strip())
        elif ch.strip():
            out.append(paragraphize(ch))
    return "\n\n".join(out)


