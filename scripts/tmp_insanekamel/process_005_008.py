NOISE = re.compile(
    r"\[(?:سرفه|نفس عمیق|خنده|مکث|نامفهوم|صدای[^\]]*|هم[^\]]*|سخن[^\]]*|"
    r"پچ[^\]]*|آیه قرآن|دعا|لغو شده[^\]]*|foreign text|سخنگوی[^\]]*)\]"
)


def clean_noise(t: str) -> str:
    t = NOISE.sub("", t)
    t = re.sub(r"[ \t]{2,}", " ", t)
    t = re.sub(r" ?\n ?", "\n", t)
    t = re.sub(r"\n{3,}", "\n\n", t)
    return t.strip()


