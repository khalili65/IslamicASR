def process_one(num: str) -> dict:
    folder = BASE / num
    cleaned = list(folder.glob("*.cleaned.txt"))[0]
    stem = cleaned.name.replace(".cleaned.txt", "")
    raw = cleaned.read_text(encoding="utf-8")
    continuous_chars = len(re.sub(r"\s+", "", raw))

    t = clean_noise(raw)
    t = apply_persian_fixes(t)
    t, log = fix_citations(t, num)
    t = apply_persian_fixes(t)  # again after citation inserts
    body = paragraphize(t)
    body_chars = len(re.sub(r"\s+", "", body))
    ratio = body_chars / max(continuous_chars, 1)

    meta = SESSIONS[num]
    corr_txt = build_corrected_txt(stem, body, log)
    corr_md = build_corrected_md(num, stem, body, meta)
    summary = build_summary(num, stem, meta)

    (folder / f"{stem}.corrected.txt").write_text(corr_txt, encoding="utf-8")
    (folder / f"{stem}.corrected.md").write_text(corr_md, encoding="utf-8")
    (folder / f"{stem}.summary.md").write_text(summary, encoding="utf-8")

    return {
        "num": num,
        "stem": stem,
        "raw_chars": continuous_chars,
        "body_chars": body_chars,
        "ratio": ratio,
        "log_n": len(log),
        "txt": folder / f"{stem}.corrected.txt",
        "md": folder / f"{stem}.corrected.md",
        "sum": folder / f"{stem}.summary.md",
    }


def main():
    results = [process_one(n) for n in ["052", "053", "054", "055", "056"]]
    for r in results:
        status = "OK" if r["ratio"] >= 0.70 else "SHORT"
        print(
            f"{r['num']}: {status} ratio={r['ratio']:.2%} "
            f"raw={r['raw_chars']} body={r['body_chars']} fixes={r['log_n']}"
        )
        print(f"  -> {r['txt'].name}, {r['md'].name}, {r['sum'].name}")


if __name__ == "__main__":
    main()
