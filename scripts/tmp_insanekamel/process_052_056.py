def ref_label(key: str) -> str:
    if key.startswith("5:"):
        return f"مائده/{key}"
    if key.startswith("3:"):
        return f"آل‌عمران/{key}"
    if key.startswith("20:"):
        return f"طه/{key}"
    if key.startswith("8:"):
        return f"انفال/{key}"
    if key.startswith("4:"):
        return f"نساء/{key}"
    if key.startswith("9:"):
        return f"توبه/{key}"
    return key


